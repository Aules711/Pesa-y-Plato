const cache = new Map();
const nrm = s => String(s).toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
export function microFor(name){
  if (cache.has(name)) return cache.get(name);
  const n = nrm(name), row = T.find(r => r[0].test(n));
  const m = row ? Object.fromEntries(MICRO_KEYS.map((k, i) => [k, row[i+1]])) : null;
  cache.set(name, m); return m;
}
// Datos de Open Food Facts (todo viene en gramos por 100 g) → nuestras unidades
export function microFromOFF(n){
  const g = k => n[k] != null && n[k] !== "" ? +n[k] : null, m = {};
  const put = (key, v, mult) => { if (v != null && isFinite(v)) m[key] = Math.round(v * mult * 100) / 100; };
  put("fib", g("fiber_100g"), 1); put("azu", g("sugars_100g"), 1); put("sat", g("saturated-fat_100g"), 1);
  put("mono", g("monounsaturated-fat_100g"), 1); put("poli", g("polyunsaturated-fat_100g"), 1); put("col", g("cholesterol_100g"), 1000);
  put("sal", g("salt_100g") ?? (g("sodium_100g") != null ? g("sodium_100g") * 2.5 : null), 1);
  put("k", g("potassium_100g"), 1000); put("ca", g("calcium_100g"), 1000); put("fe", g("iron_100g"), 1000); put("mg", g("magnesium_100g"), 1000);
  put("vc", g("vitamin-c_100g"), 1000); put("va", g("vitamin-a_100g"), 1e6); put("vd", g("vitamin-d_100g"), 1e6); put("b12", g("vitamin-b12_100g"), 1e6); put("fol", g("vitamin-b9_100g") ?? g("folates_100g"), 1e6);
  return Object.keys(m).length ? m : null;
}
